        el('p', null, 'The watchlist is the floor: every protocol with at least $', el('b', { text: Math.round(DATA.floor_usd / 1e6) + 'M' }), ' of TVL and no token on record. The early radar adds ', el('b', { text: String(DATA.early_size) }), ' launch candidates below that floor, and ', el('b', { text: String(DATA.live_size) }), ' live-token protocols are set aside with their market caps. Implied value is a model, not a promise and not a price.')
